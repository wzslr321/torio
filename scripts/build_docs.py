def diff_outputs(rendered: dict[str, str], on_disk: dict[str, str]) -> list[str]:
    problems: list[str] = []
    for path in sorted(rendered):
        if path not in on_disk:
            problems.append(f"{path}: generated file is missing")
        elif on_disk[path] != rendered[path]:
            problems.append(f"{path}: generated file is stale")
    return problems


def read_on_disk(paths: list[str]) -> dict[str, str]:
    found: dict[str, str] = {}
    for path in paths:
        full = ROOT / path
        if full.exists():
            found[path] = full.read_text(encoding="utf-8")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="render in memory and fail if any generated file is stale; writes nothing",
    )
    args = parser.parse_args(argv)

    try:
        rendered = build()
    except BuildError as exc:
        print(f"docs build FAILED: {exc}", file=sys.stderr)
        return 1

    if args.check:
        problems = diff_outputs(rendered, read_on_disk(list(rendered)))
        if problems:
            print("docs build check FAILED — regenerate with: python3 scripts/build_docs.py")
            for problem in problems:
                print(f"  - {problem}")
            return 1
        print(f"docs build check OK: {len(rendered)} generated files match their sources")
        return 0

    for path, text in sorted(rendered.items()):
        full = ROOT / path
        full.parent.mkdir(parents=True, exist_ok=True)
        full.write_text(text, encoding="utf-8")
    print(f"docs build OK: wrote {len(rendered)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
