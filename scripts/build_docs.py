def slug(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-")


SHELL_LANGS = {"bash", "sh", "shell", "console"}


def highlight_shell(line: str) -> str:
    """Tint one shell line: quoted strings and trailing comments.

    Deliberately not a shell parser. These blocks are commands to be pasted
    verbatim, and the two things a reader needs to separate at a glance are
    "this part is an explanatory comment, do not type it" and "this argument is
    one quoted unit". Guessing at builtins or variables would add colour
    without adding meaning, and would be wrong often enough to mislead.
    """
    out: list[str] = []
    plain: list[str] = []
    index = 0

    def flush() -> None:
        if plain:
            out.append(html.escape("".join(plain), quote=False))
            plain.clear()

    while index < len(line):
        char = line[index]

        if char in "'\"":
            end = line.find(char, index + 1)
            end = len(line) if end == -1 else end + 1
            flush()
            quoted = html.escape(line[index:end], quote=False)
            out.append(f'<span class="tok-str">{quoted}</span>')
            index = end
            continue

        # A comment only starts at a word boundary, so a URL fragment and a
        # printf format like '%h#x' stay untouched.
        if char == "#" and (index == 0 or line[index - 1].isspace()):
            flush()
            comment = html.escape(line[index:], quote=False)
            out.append(f'<span class="tok-comment">{comment}</span>')
            return "".join(out)

        plain.append(char)
        index += 1

    flush()
    return "".join(out)


def render_inline(text: str) -> str:
    """Render inline markup, protecting code spans from further processing."""
    spans: list[str] = []

    def stash(match: re.Match[str]) -> str:
        spans.append(html.escape(match.group(1), quote=False))
        return f"\x00{len(spans) - 1}\x00"

    text = re.sub(r"`([^`]+)`", stash, text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)([^*]+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: f"<code>{spans[int(m.group(1))]}</code>", text)


def _render_cells(row: str) -> list[str]:
    return [render_inline(cell.strip()) for cell in row.strip().strip("|").split("|")]


def render_markdown(text: str) -> str:
    """Render the Markdown subset the Torio docs actually use.

    Supported: ATX headings (with optional ``{#anchor}``), paragraphs, fenced
    code, unordered and ordered lists, pipe tables, blockquotes (rendered as
    the site's callout), raw HTML blocks, and inline code/links/strong/em.
    """
    lines = text.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    i = 0

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if not stripped:
            i += 1
            continue

        fence = FENCE.match(stripped)
        if fence:
            lang = fence.group(1)
            i += 1
            body: list[str] = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                body.append(lines[i])
                i += 1
            i += 1  # closing fence

            if lang in SHELL_LANGS:
                code = "\n".join(highlight_shell(line) for line in body)
            else:
                code = html.escape("\n".join(body), quote=False)
            attr = f' data-lang="{html.escape(lang, quote=True)}"' if lang else ""
            out.append(f'<div class="code-block"><pre{attr}><code>{code}</code></pre></div>')
            continue

        heading = HEADING.match(stripped)
        if heading:
            hashes, title, explicit = heading.groups()
            level = len(hashes)
            anchor = explicit or slug(title)
            out.append(f'<h{level} id="{anchor}">{render_inline(title)}</h{level}>')
            i += 1
            continue

        if stripped.startswith("|") and i + 1 < len(lines) and TABLE_SEP.match(lines[i + 1].strip()):
            header = _render_cells(stripped)
            i += 2
            rows: list[list[str]] = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_render_cells(lines[i].strip()))
                i += 1
            head = "".join(f"<th>{cell}</th>" for cell in header)
            body_html = "".join(
                "<tr>" + "".join(f"<td>{cell}</td>" for cell in row) + "</tr>" for row in rows
            )
            out.append(
                '<div class="table-scroll"><table><thead><tr>'
                f"{head}</tr></thead><tbody>{body_html}</tbody></table></div>"
            )
            continue

        if stripped.startswith(">"):
            quoted: list[str] = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quoted.append(lines[i].strip()[1:].lstrip())
                i += 1
            out.append(f'<div class="callout">{render_markdown(chr(10).join(quoted))}</div>')
            continue

        if UL_ITEM.match(stripped) or OL_ITEM.match(stripped):
            ordered = bool(OL_ITEM.match(stripped))
            items: list[str] = []
            while i < len(lines):
                candidate = lines[i]
                match = OL_ITEM.match(candidate.strip()) if ordered else UL_ITEM.match(candidate.strip())
                if not match:
                    # continuation line of the previous item
                    if items and candidate.startswith(("  ", "\t")) and candidate.strip():
                        items[-1] += " " + candidate.strip()
                        i += 1
                        continue
                    break
                items.append(match.group(2) if ordered else match.group(1))
                i += 1
            tag = "ol" if ordered else "ul"
            rendered = "".join(f"<li>{render_inline(item)}</li>" for item in items)
            out.append(f"<{tag}>{rendered}</{tag}>")
            continue

        if stripped.startswith("<"):
            raw: list[str] = []
            while i < len(lines) and lines[i].strip():
                raw.append(lines[i])
                i += 1
            out.append("\n".join(raw))
            continue

        para: list[str] = []
        while i < len(lines) and lines[i].strip() and not _starts_block(lines[i].strip()):
            para.append(lines[i].strip())
            i += 1
        out.append(f"<p>{render_inline(' '.join(para))}</p>")

    return "\n".join(out)


def _starts_block(stripped: str) -> bool:
    return bool(
        FENCE.match(stripped)
        or HEADING.match(stripped)
        or UL_ITEM.match(stripped)
        or OL_ITEM.match(stripped)
        or stripped.startswith(("|", ">", "<"))
    )


