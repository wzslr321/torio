#!/usr/bin/env python3
"""Single-source documentation generator for Torio.

Prose lives once, under ``docs/content/``:

  * ``blocks/``   — shareable sections, each addressed by its filename stem;
  * ``pages/``    — site page sources, rendered to ``site/*.html``;
  * ``runbooks/`` — runbook sources, rendered to ``docs/runbooks/*.md``.

A page or runbook pulls a block in with ``<!-- include: block-id -->``. Because
both outputs expand the *same* block file, a section shared by the getting
started page and the reference page cannot drift: there is only one copy.

Standard library only, matching the other scripts here. Two modes:

    python3 scripts/build_docs.py            # write the generated outputs
    python3 scripts/build_docs.py --check    # render in memory, diff, never write

``--check`` performs no writes and no network access, so it is safe to run as a
validation gate.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "docs" / "content"
LAYOUT = CONTENT / "_layout.html"

# Where this project lives. Every generated page links back to it, so the slug
# is written once here rather than once per page: moving the repository to an
# organisation is then one edit plus ``make docs``.
#
# Deliberately not overridable by the environment, unlike ``TORIO_REPO`` in
# scripts/install.sh. That installer resolves assets at run time on someone
# else's machine; this generator writes files that are committed and diffed by
# ``--check``. An environment-dependent output would make the drift gate report
# a different answer per machine, which is worse than a constant to edit.
REPO_SLUG = "wzslr321/torio"
REPO_URL = f"https://github.com/{REPO_SLUG}"

BANNER_HTML = (
    "<!-- Generated by scripts/build_docs.py from {source} — do not edit.\n"
    "     Edit the source and re-run: python3 scripts/build_docs.py -->"
)
BANNER_MD = (
    "<!-- Generated by scripts/build_docs.py from {source} — do not edit.\n"
    "     Edit the source and re-run: python3 scripts/build_docs.py -->"
)

INCLUDE = re.compile(
    r"^[ \t]*<!--[ \t]*include:[ \t]*([A-Za-z0-9_-]+)"
    r"(?:[ \t]+level=(\d))?"
    r'(?:[ \t]+heading="([^"]*)")?'
    r"[ \t]*-->[ \t]*$",
    re.MULTILINE,
)
FRONT_MATTER = re.compile(r"\A---[ \t]*\n(.*?)\n---[ \t]*\n", re.DOTALL)
HEADING = re.compile(r"^(#{1,6})[ \t]+(.*?)[ \t]*(?:\{#([A-Za-z0-9_-]+)\})?[ \t]*$")
FENCE = re.compile(r"^```[ \t]*([A-Za-z0-9_+-]*)[ \t]*$")
TABLE_SEP = re.compile(r"^\|[ \t:|-]+\|$")
TOC = re.compile(r"^[ \t]*<!--[ \t]*toc[ \t]*-->[ \t]*$", re.MULTILINE)
OL_ITEM = re.compile(r"^(\d+)\.[ \t]+(.*)$")
UL_ITEM = re.compile(r"^[-*][ \t]+(.*)$")

MAX_INCLUDE_DEPTH = 16


class BuildError(Exception):
    """A source problem that must stop the build rather than be papered over."""


@dataclass
class Block:
    id: str
    meta: dict[str, str]
    body: str


@dataclass
class Page:
    source: Path
    meta: dict[str, str]
    body: str
    outputs: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------
# sources
# --------------------------------------------------------------------------


def parse_source(text: str, where: str) -> tuple[dict[str, str], str]:
    """Split optional ``---`` front matter from the body.

    Front matter is a flat ``key: value`` mapping; nothing here needs nesting,
    and refusing to invent a YAML subset keeps the format unambiguous.
    """
    match = FRONT_MATTER.match(text)
    if not match:
        return {}, text

    meta: dict[str, str] = {}
    for lineno, line in enumerate(match.group(1).splitlines(), start=2):
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise BuildError(f"{where}:{lineno}: front matter line is not 'key: value': {line!r}")
        value = value.strip()
        # Quoting is how a value carries a colon of its own.
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[key.strip()] = value
    return meta, text[match.end() :]


def load_blocks() -> dict[str, Block]:
    blocks: dict[str, Block] = {}
    block_dir = CONTENT / "blocks"
    if not block_dir.is_dir():
        raise BuildError(f"no block directory at {block_dir.relative_to(ROOT)}")
    for path in sorted(block_dir.glob("*.md")):
        meta, body = parse_source(path.read_text(encoding="utf-8"), where=str(path.relative_to(ROOT)))
        blocks[path.stem] = Block(id=path.stem, meta=meta, body=body)
    if not blocks:
        raise BuildError(f"no blocks found in {block_dir.relative_to(ROOT)}")
    return blocks


def shift_headings(text: str, top_level: int) -> str:
    """Re-level a block so its shallowest heading sits at ``top_level``.

    A block is written once but appears at different depths — a step inside the
    getting started page, a top-level section in the reference. Shifting on
    include lets one source serve both. Fenced code is skipped so a shell
    comment is never mistaken for a heading.
    """
    lines = text.split("\n")
    in_fence = False
    levels: list[int] = []
    for line in lines:
        if FENCE.match(line.strip()):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = HEADING.match(line.strip())
        if heading:
            levels.append(len(heading.group(1)))
    if not levels:
        return text

    delta = top_level - min(levels)
    if delta == 0:
        return text

    out: list[str] = []
    in_fence = False
    for line in lines:
        if FENCE.match(line.strip()):
            in_fence = not in_fence
            out.append(line)
            continue
        heading = HEADING.match(line.strip()) if not in_fence else None
        if heading:
            level = max(1, min(6, len(heading.group(1)) + delta))
            out.append("#" * level + line.strip()[len(heading.group(1)) :])
        else:
            out.append(line)
    return "\n".join(out)


def expand_toc(text: str) -> str:
    """Replace a ``<!-- toc -->`` marker with a list of the document's steps.

    Generated rather than hand-written so a long single page can be scanned
    without the contents list becoming another thing that drifts.
    """
    if not TOC.search(text):
        return text

    entries: list[str] = []
    in_fence = False
    for line in text.split("\n"):
        if FENCE.match(line.strip()):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = HEADING.match(line.strip())
        if heading and len(heading.group(1)) == 3:
            title = heading.group(2)
            anchor = heading.group(3) or slug(title)
            entries.append(f"- [{title}](#{anchor})")
    return TOC.sub("\n".join(entries) if entries else "", text)


def strip_anchor_syntax(text: str) -> str:
    """Drop ``{#anchor}`` heading suffixes, which only mean something in HTML."""
    lines = text.split("\n")
    in_fence = False
    out: list[str] = []
    for line in lines:
        if FENCE.match(line.strip()):
            in_fence = not in_fence
            out.append(line)
            continue
        heading = HEADING.match(line.strip()) if not in_fence else None
        if heading and heading.group(3):
            out.append(f"{heading.group(1)} {heading.group(2)}")
        else:
            out.append(line)
    return "\n".join(out)


def check_block_portability(blocks: dict[str, Block]) -> list[str]:
    """Reject links that cannot survive both output formats.

    A block is rendered into site HTML *and* into runbook Markdown. A
    ``page.html`` link resolves on the site but dangles from a runbook, so
    cross-page links belong in the including page's own prose, not in a shared
    block. Fragment-only and absolute links travel fine.
    """
    problems: list[str] = []
    for block_id in sorted(blocks):
        for target in re.findall(r"\[[^\]]*\]\(([^)]+)\)", blocks[block_id].body):
            if target.split("#", 1)[0].endswith(".html"):
                problems.append(
                    f"blocks/{block_id}.md: shared blocks cannot link to {target!r} — "
                    "site-relative links dangle in the generated runbooks; "
                    "move the cross-reference into the including page"
                )
    return problems


def retitle_first_heading(text: str, title: str) -> str:
    """Rename a block's own top heading, keeping its level and anchor.

    Lets a numbered step ("Step 1 — Build the CLI") reuse a block that calls
    itself something else elsewhere, without the page having to add a second
    heading above the included one.
    """
    lines = text.split("\n")
    for index, line in enumerate(lines):
        heading = HEADING.match(line.strip())
        if not heading:
            continue
        anchor = f" {{#{heading.group(3)}}}" if heading.group(3) else ""
        lines[index] = f"{heading.group(1)} {title}{anchor}"
        break
    return "\n".join(lines)


def expand_includes(text: str, blocks: dict[str, Block], where: str, depth: int = 0) -> str:
    """Expand ``<!-- include: id [level=N] [heading="…"] -->`` markers."""
    if depth > MAX_INCLUDE_DEPTH:
        raise BuildError(f"{where}: include nesting exceeded {MAX_INCLUDE_DEPTH} levels (cycle?)")

    def replace(match: re.Match[str]) -> str:
        block_id, level, heading = match.group(1), match.group(2), match.group(3)
        block = blocks.get(block_id)
        if block is None:
            known = ", ".join(sorted(blocks)) or "none"
            raise BuildError(f"{where}: unknown block {block_id!r} (known: {known})")
        body = block.body.strip("\n")
        if level:
            body = shift_headings(body, int(level))
        if heading:
            body = retitle_first_heading(body, heading)
        return expand_includes(body, blocks, where=f"{where} -> {block_id}", depth=depth + 1)

    return INCLUDE.sub(replace, text)


