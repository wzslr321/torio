def load_pages(subdir: str) -> list[Page]:
    pages: list[Page] = []
    directory = CONTENT / subdir
    if not directory.is_dir():
        raise BuildError(f"no source directory at {directory.relative_to(ROOT)}")
    for path in sorted(directory.glob("*.md")):
        meta, body = parse_source(path.read_text(encoding="utf-8"), where=str(path.relative_to(ROOT)))
        for required in ("output",):
            if required not in meta:
                raise BuildError(f"{path.relative_to(ROOT)}: front matter is missing '{required}'")
        pages.append(Page(source=path, meta=meta, body=body))
    return pages


def nav_html(pages: list[Page], current: str) -> str:
    items: list[str] = []
    for page in sorted(pages, key=lambda p: int(p.meta.get("order", "99"))):
        if "nav" not in page.meta:
            continue
        href = Path(page.meta["output"]).name
        current_attr = ' aria-current="page"' if href == current else ""
        items.append(f'<li><a href="{href}"{current_attr}>{html.escape(page.meta["nav"])}</a></li>')
    return "\n            ".join(items)


def render_page(page: Page, pages: list[Page], blocks: dict[str, Block], layout: str) -> str:
    where = str(page.source.relative_to(ROOT))
    body = expand_toc(expand_includes(page.body, blocks, where=where))
    output_name = Path(page.meta["output"]).name

    scope = page.meta.get("scope_notice", "")
    scope_html = (
        f'<div class="wrap">\n        <p class="scope-notice">{render_inline(scope)}</p>\n      </div>'
        if scope
        else ""
    )
    kicker = page.meta.get("kicker", "")
    kicker_html = f'<span class="mode-kicker">{html.escape(kicker)}</span>\n        ' if kicker else ""

    rendered = layout
    replacements = {
        "banner": BANNER_HTML.format(source=where),
        "title": html.escape(page.meta.get("title", "Torio")),
        "description": html.escape(page.meta.get("description", "")),
        "page_id": Path(output_name).stem,
        "nav": nav_html(pages, output_name),
        "scope_notice": scope_html,
        "kicker": kicker_html,
        "content": render_markdown(body),
        "repo_url": REPO_URL,
    }
    for key, value in replacements.items():
        rendered = rendered.replace("{{" + key + "}}", value)

    leftover = re.search(r"\{\{([a-z_]+)\}\}", rendered)
    if leftover:
        raise BuildError(f"{where}: layout placeholder {{{{{leftover.group(1)}}}}} was never filled")
    return rendered.rstrip() + "\n"


def render_runbook(page: Page, blocks: dict[str, Block]) -> str:
    where = str(page.source.relative_to(ROOT))
    body = strip_anchor_syntax(expand_toc(expand_includes(page.body, blocks, where=where)))
    return BANNER_MD.format(source=where) + "\n\n" + body.strip("\n") + "\n"


def build() -> dict[str, str]:
    blocks = load_blocks()
    problems = check_block_portability(blocks)
    if problems:
        raise BuildError("shared blocks are not portable:\n  - " + "\n  - ".join(problems))
    site_pages = load_pages("pages")
    runbooks = load_pages("runbooks")
    layout = LAYOUT.read_text(encoding="utf-8")

    outputs: dict[str, str] = {}
    for page in site_pages:
        outputs[page.meta["output"]] = render_page(page, site_pages, blocks, layout)
    for page in runbooks:
        outputs[page.meta["output"]] = render_runbook(page, blocks)
    return outputs


